static HAL_StatusTypeDef WriteCmd(uint8_t cmd)
{
  uint8_t data[2] = {0x00, cmd};
  return HAL_I2C_Master_Transmit(s_hi2c, SSD1306_I2C_ADDR, data, 2, 100);
}

static void DrawChar(char c)
{
  if (c < 32 || c > 90)
  {
    c = '?';
  }
  if (s_x > SSD1306_WIDTH - 6 || s_page > 7)
  {
    return;
  }

  const uint8_t *g = Font5x7[c - 32];
  for (uint8_t i = 0; i < 5; i++)
  {
    s_buf[s_page * SSD1306_WIDTH + s_x + i] = g[i];
  }
  s_buf[s_page * SSD1306_WIDTH + s_x + 5] = 0x00;
  s_x = (uint8_t)(s_x + 6);
}

HAL_StatusTypeDef SSD1306_Init(I2C_HandleTypeDef *hi2c)
{
  s_hi2c = hi2c;
  HAL_Delay(50);

  if (HAL_I2C_IsDeviceReady(s_hi2c, SSD1306_I2C_ADDR, 3, 100) != HAL_OK)
  {
    return HAL_ERROR;
  }

  static const uint8_t init[] = {
    0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
    0x8D, 0x14, 0x20, 0x00, 0xA1, 0xC8, 0xDA, 0x12,
    0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF
  };

  for (uint32_t i = 0; i < sizeof(init); i++)
  {
    if (WriteCmd(init[i]) != HAL_OK)
    {
      return HAL_ERROR;
    }
  }

  SSD1306_Clear();
  SSD1306_Update();
  return HAL_OK;
}

void SSD1306_Clear(void)
{
  memset(s_buf, 0, sizeof(s_buf));
  s_x = 0;
  s_page = 0;
}

void SSD1306_SetCursor(uint8_t x, uint8_t page)
{
  s_x = x;
  s_page = page;
}

void SSD1306_WriteString(const char *s)
{
  while (*s)
  {
    char c = *s++;
    if (c >= 'a' && c <= 'z')
    {
      c = (char)(c - 32);
    }
    DrawChar(c);
  }
}

void SSD1306_Update(void)
{
  for (uint8_t page = 0; page < 8; page++)
  {
    WriteCmd((uint8_t)(0xB0 + page));
    WriteCmd(0x00);
    WriteCmd(0x10);

    uint8_t packet[1 + SSD1306_WIDTH];
    packet[0] = 0x40;
    memcpy(&packet[1], &s_buf[page * SSD1306_WIDTH], SSD1306_WIDTH);
    HAL_I2C_Master_Transmit(s_hi2c, SSD1306_I2C_ADDR, packet, sizeof(packet), 100);
  }
}
